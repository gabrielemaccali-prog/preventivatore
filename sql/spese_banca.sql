-- ============================================================
-- Spese di BFM ed estratto conto della banca.
-- Da eseguire nell'SQL Editor di Supabase, e subito dopo sql/spese_classificazione.sql, che
-- sostituisce categoria + centro di costo con la classificazione a tre livelli.
--
-- Le spese si scrivono a mano o nascono dai movimenti dell'estratto conto. Ognuna ha una
-- categoria e un centro di costo, decisi dal Configuratore; finche' manca uno dei due la spesa e'
-- "da completare". Le regole classificano da sole i movimenti ricorrenti (canone, TIM, compensi
-- dei bubbler...).
--
--   spese_categorie   le categorie delle spese
--   spese_centri      i centri di costo; quello con "albatros" manda le sue spese anche in Albatros
--   banca_import      ogni caricamento del file, con i saldi che dichiara (servono al controllo)
--   banca_movimenti   le righe dell'estratto conto, una volta sola anche se il file si ricarica
--   spese             le spese
--   spese_regole      le regole di classificazione dei movimenti
--
-- IL FILE SI PUO' RICARICARE QUANTE VOLTE SI VUOLE, anche su date gia' caricate: ogni movimento ha
-- una "impronta" unica (tipo + codice della disposizione, o i suoi dati quando il codice non c'e'),
-- e l'app inserisce solo le impronte nuove. Le altre si saltano senza errori.
--
-- Additiva: non tocca nessuna tabella esistente, salvo una colonna nuova su albatros_spese.
-- ============================================================

begin;
set local lock_timeout = '3s';

create table if not exists spese_categorie (
  id bigint generated by default as identity primary key,
  nome text not null check (btrim(nome) <> ''),
  ordine integer not null default 0,
  attiva boolean not null default true,
  creato_il timestamptz not null default now()
);
create unique index if not exists spese_categorie_nome_idx on spese_categorie (lower(btrim(nome)));

create table if not exists spese_centri (
  id bigint generated by default as identity primary key,
  nome text not null check (btrim(nome) <> ''),
  ordine integer not null default 0,
  attivo boolean not null default true,
  -- Le spese di questo centro sono costi di gestione di Albatros: finiscono anche fra le spese di
  -- Albatros, pagate da BFM (vedi albatros_spese.spesa_bfm_id).
  albatros boolean not null default false,
  creato_il timestamptz not null default now()
);
create unique index if not exists spese_centri_nome_idx on spese_centri (lower(btrim(nome)));

insert into spese_categorie (nome, ordine)
values ('Compensi bubbler', 1), ('Affitti campi', 2), ('Affitto sede', 3), ('Fornitori e noleggi', 4),
       ('Materiali', 5), ('Software e hosting', 6), ('Utenze', 7), ('Imposte e contributi', 8),
       ('Oneri bancari', 9), ('Rimborsi note spese', 10), ('Consulenze e notaio', 11),
       ('Rappresentanza', 12), ('Altro', 13)
on conflict do nothing;

insert into spese_centri (nome, ordine, albatros)
values ('Bubble Football', 1, false), ('Calciobalilla umano', 2, false), ('Albatros', 3, true), ('Generale', 4, false)
on conflict do nothing;

-- ------------------------------------------------------------
-- CARICAMENTI: uno per file caricato. I saldi dichiarati dal file permettono di controllare che
-- fra un caricamento e l'altro non manchi nessun pezzo di estratto conto.
-- ------------------------------------------------------------
create table if not exists banca_import (
  id bigint generated by default as identity primary key,
  file_nome text,
  conto text,
  dal date not null,
  al date not null,
  saldo_iniziale numeric(12,2) not null,      -- prima dei movimenti del giorno "dal"
  saldo_finale numeric(12,2) not null,        -- dopo i movimenti del giorno "al"
  righe_lette integer not null default 0,
  righe_nuove integer not null default 0,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null,
  constraint banca_import_intervallo_valido check (al >= dal)
);

-- ------------------------------------------------------------
-- MOVIMENTI: le righe contabilizzate dell'estratto conto. Le "non contabilizzate" non entrano:
-- arrivano contabilizzate nel file successivo, spesso con una descrizione diversa.
-- importo con segno: positivo un accredito, negativo un addebito.
-- ------------------------------------------------------------
create table if not exists banca_movimenti (
  id bigint generated by default as identity primary key,
  impronta text not null,
  codice text,                                -- codice della disposizione, quando c'e'
  data_contabile date not null,
  data_valuta date,
  tipo text not null,                         -- la "Descrizione" della banca: PAGAMENTO POS, ...
  descrizione text,                           -- la "Descrizione estesa"
  importo numeric(12,2) not null check (importo <> 0),
  import_id bigint references banca_import(id) on delete set null,
  -- Commissione o costo di un'altra uscita (il costo di un bonifico): non e' una spesa a se', si
  -- somma alla spesa principale come oneri bancari.
  onere_spesa_id bigint,
  -- Movimento che non e' una spesa (un giroconto, un errore stornato): resta in elenco, e basta.
  ignorato boolean not null default false,
  note text,
  creato_il timestamptz not null default now()
);
create unique index if not exists banca_movimenti_impronta_idx on banca_movimenti (impronta);
create index if not exists banca_movimenti_data_idx on banca_movimenti (data_contabile);
create index if not exists banca_movimenti_codice_idx on banca_movimenti (codice);

-- ------------------------------------------------------------
-- SPESE. Una spesa nata dalla banca ha il suo movimento (movimento_id, unico: un movimento non
-- diventa due spese, nemmeno se l'elaborazione parte due volte). Una scritta a mano puo' essere
-- collegata dopo al movimento che la paga.
-- ------------------------------------------------------------
create table if not exists spese (
  id bigint generated by default as identity primary key,
  data date not null,
  importo numeric(12,2) not null check (importo > 0),   -- senza oneri: quelli sono i movimenti collegati
  descrizione text not null check (btrim(descrizione) <> ''),
  beneficiario text,
  categoria_id bigint references spese_categorie(id) on delete restrict,
  centro_id bigint references spese_centri(id) on delete restrict,
  -- Come e' stata pagata: 'conto' (deve comparire nell'estratto conto) | 'contanti' | 'altro'.
  metodo text not null default 'conto' check (metodo in ('conto', 'contanti', 'altro')),
  origine text not null default 'manuale' check (origine in ('manuale', 'banca')),
  movimento_id bigint references banca_movimenti(id) on delete set null,
  regola_id bigint,                           -- la regola che l'ha classificata, se e' stata una regola
  -- La categoria con cui la spesa compare in Albatros, quando il centro e' quello di Albatros.
  albatros_categoria_id bigint references albatros_categorie(id) on delete set null,
  note text,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);
create unique index if not exists spese_movimento_idx on spese (movimento_id);
create index if not exists spese_data_idx on spese (data);

alter table banca_movimenti drop constraint if exists banca_movimenti_onere_spesa_fk;
alter table banca_movimenti add constraint banca_movimenti_onere_spesa_fk
  foreign key (onere_spesa_id) references spese(id) on delete set null;

-- ------------------------------------------------------------
-- REGOLE. Si provano in ordine e vale la prima che corrisponde. Le condizioni scritte valgono
-- tutte insieme; ognuna accetta piu' alternative separate da "|" (es. "OVH|SITEGROUND").
--   tipo_contiene        nel tipo del movimento (la "Descrizione" della banca)
--   testo_contiene       nella descrizione estesa
--   beneficiario_bubbler il bonifico e' a favore di un bubbler (riconosciuto per nome e cognome)
--   azione 'spesa'       crea la spesa con categoria e centro (vuoti = la spesa resta da completare)
--   azione 'ignora'      il movimento non e' una spesa
-- ------------------------------------------------------------
create table if not exists spese_regole (
  id bigint generated by default as identity primary key,
  nome text not null check (btrim(nome) <> ''),
  ordine integer not null default 0,
  attiva boolean not null default true,
  segno text not null default 'uscita' check (segno in ('uscita', 'entrata')),
  tipo_contiene text,
  testo_contiene text,
  beneficiario_bubbler boolean not null default false,
  azione text not null default 'spesa' check (azione in ('spesa', 'ignora')),
  categoria_id bigint references spese_categorie(id) on delete set null,
  centro_id bigint references spese_centri(id) on delete set null,
  descrizione text,                           -- descrizione da dare alla spesa; vuota = dal movimento
  creato_il timestamptz not null default now()
);

alter table spese drop constraint if exists spese_regola_fk;
alter table spese add constraint spese_regola_fk foreign key (regola_id) references spese_regole(id) on delete set null;

-- Le regole di partenza, scritte sui movimenti dell'estratto conto di luglio-ottobre 2026.
insert into spese_regole (nome, ordine, tipo_contiene, testo_contiene, beneficiario_bubbler, categoria_id, centro_id, descrizione)
select v.nome, v.ordine, v.tipo, v.testo, v.bubbler,
       (select id from spese_categorie where nome = v.categoria),
       (select id from spese_centri where nome = v.centro), v.descrizione
  from (values
    ('Compensi dei bubbler', 1, 'BONIFICO', 'COMPENSI', true, 'Compensi bubbler', null, null),
    ('Rimborsi note spese', 2, 'BONIFICO', 'NOTE SPESE', false, 'Rimborsi note spese', 'Generale', null),
    ('Telefono TIM', 3, 'ADUE', 'TIM SPA', false, 'Utenze', 'Generale', 'TIM'),
    ('Hosting e server', 4, null, 'OVH|SITEGROUND', false, 'Software e hosting', 'Generale', null),
    ('Deleghe F24', 5, 'F24', null, false, 'Imposte e contributi', 'Generale', 'Delega F24'),
    ('Canone, bolli e competenze', 6, 'CANONE|BOLLO|COMPETENZE', null, false, 'Oneri bancari', 'Generale', null),
    ('Commissioni senza bonifico', 7, 'COSTO|COMMISSIONE', null, false, 'Oneri bancari', 'Generale', null)
  ) as v(nome, ordine, tipo, testo, bubbler, categoria, centro, descrizione)
 where not exists (select 1 from spese_regole);

-- ------------------------------------------------------------
-- ALBATROS. Una spesa di BFM sul centro di Albatros compare anche fra le spese di Albatros, pagata
-- da BFM: e' lo stesso costo visto da due lati, non due costi. Per BFM e' un'uscita del conto; per
-- Albatros e' un costo di gestione, che BFM ha anticipato. Chi somma i costi di tutte e due deve
-- saltare le righe di albatros_spese che hanno spesa_bfm_id.
-- La scrive e la aggiorna il modulo Spese; se la spesa sparisce, o cambia centro, sparisce anche qui.
-- ------------------------------------------------------------
alter table albatros_spese add column if not exists spesa_bfm_id bigint references spese(id) on delete cascade;
-- Una spesa di BFM compare in Albatros una volta sola. I null (le spese scritte in Albatros) restano liberi.
create unique index if not exists albatros_spese_spesa_bfm_idx on albatros_spese (spesa_bfm_id);

-- Chiuse a chi non e' entrato, come tutte le tabelle (vedi sql/accesso_supabase_auth.sql).
alter table spese_categorie enable row level security;
drop policy if exists app_accesso on spese_categorie;
create policy app_accesso on spese_categorie for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));
alter table spese_centri enable row level security;
drop policy if exists app_accesso on spese_centri;
create policy app_accesso on spese_centri for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));
alter table banca_import enable row level security;
drop policy if exists app_accesso on banca_import;
create policy app_accesso on banca_import for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));
alter table banca_movimenti enable row level security;
drop policy if exists app_accesso on banca_movimenti;
create policy app_accesso on banca_movimenti for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));
alter table spese enable row level security;
drop policy if exists app_accesso on spese;
create policy app_accesso on spese for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));
alter table spese_regole enable row level security;
drop policy if exists app_accesso on spese_regole;
create policy app_accesso on spese_regole for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

commit;

-- Controllo: categorie, centri e regole di partenza; nessun movimento e nessuna spesa.
select (select count(*) from spese_categorie) as categorie,
       (select count(*) from spese_centri) as centri,
       (select count(*) from spese_regole) as regole,
       (select count(*) from banca_movimenti) as movimenti,
       (select count(*) from spese) as spese;
