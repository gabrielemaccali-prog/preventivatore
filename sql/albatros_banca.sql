-- ============================================================
-- Albatros: le spese dal suo conto in banca (estratto conto "Lista Movimenti" in Excel).
-- Da eseguire nell'SQL Editor di Supabase.
--
-- Il conto di Albatros è un altro da quello di BFM: i suoi movimenti stanno in tabelle loro, non
-- in banca_movimenti. Per ora entrano solo le uscite, dal 1 ottobre 2026 (prima il conto
-- teneva altro): ognuna diventa una spesa di Albatros pagata dal conto (metodo 'carta' per i
-- pagamenti POS, 'conto' per bonifici, addebiti e oneri). Gli incassi (SumUp, versamenti) per
-- ora no: l'incasso resta quello delle chiusure.
-- Le spese con carta già scritte a mano si abbinano al loro movimento invece di contarle due volte.
--
--   albatros_banca_import      un file caricato: periodo, saldi, chi
--   albatros_banca_movimenti   i movimenti del file dal 1 ottobre, una volta sola anche ricaricando
--                              (impronta); le entrate restano lì, senza spesa
--   albatros_spese.movimento_id  la spesa nata da un movimento (o una scritta a mano prima,
--                                abbinata al suo movimento)
--   albatros_trasferimenti.movimento_id  un movimento che non è una spesa ma un trasferimento:
--                                un prelievo in contanti dal conto (da = 'conto')
--   albatros_banca_movimenti.onere_spesa_id  la commissione di un bonifico o di un addebito: non
--                                è una spesa a sé, il suo importo è sommato alla spesa di quel
--                                movimento (stesso codice di disposizione)
-- Serve dopo sql/albatros_trasferimenti.sql.
-- ============================================================

begin;
set local lock_timeout = '3s';

create table if not exists albatros_banca_import (
  id bigint generated by default as identity primary key,
  nome_file text,
  conto text,
  dal date,
  al date,
  saldo_iniziale numeric(12,2),
  saldo_finale numeric(12,2),
  movimenti int not null default 0,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);

create table if not exists albatros_banca_movimenti (
  id bigint generated by default as identity primary key,
  impronta text not null,
  data_contabile date not null,
  data_valuta date,
  tipo text,
  descrizione text,
  importo numeric(12,2) not null,
  import_id bigint references albatros_banca_import(id) on delete set null,
  creato_il timestamptz not null default now()
);
create unique index if not exists albatros_banca_movimenti_impronta_idx on albatros_banca_movimenti (impronta);

alter table albatros_spese add column if not exists movimento_id bigint references albatros_banca_movimenti(id) on delete set null;
create unique index if not exists albatros_spese_movimento_idx on albatros_spese (movimento_id);

-- Un'operazione non ancora contabilizzata (NC): entra come le altre, e quando un file successivo la
-- contabilizza la sua spesa passa al movimento contabilizzato e questa se ne va.
alter table albatros_banca_movimenti add column if not exists non_contabilizzato boolean not null default false;
-- Un movimento che non è una spesa (un giroconto, un errore stornato): resta in elenco, e basta.
alter table albatros_banca_movimenti add column if not exists ignorato boolean not null default false;
-- Le entrate si classificano nella vista Entrate: 'pos' (incasso POS delle chiusure, accreditato
-- da SumUp) o 'altro' (un'altra entrata, spiegata in entrata_nota). Un versamento di contanti è un
-- trasferimento (albatros_trasferimenti.movimento_id, da = 'contanti'); un'entrata da non contare
-- si ignora. Senza nessuna delle tre è da completare.
alter table albatros_banca_movimenti add column if not exists entrata text check (entrata in ('pos', 'altro'));
alter table albatros_banca_movimenti add column if not exists entrata_nota text;
-- Il saldo del conto alla fine del 30 settembre 2026, ricostruito dal primo file: da lì si
-- ricostruisce il saldo con i movimenti, per controllare che non manchi un pezzo di estratto.
alter table albatros_banca_import add column if not exists saldo_inizio numeric(12,2);

alter table albatros_banca_movimenti add column if not exists onere_spesa_id bigint references albatros_spese(id) on delete set null;

alter table albatros_trasferimenti add column if not exists movimento_id bigint references albatros_banca_movimenti(id) on delete set null;
create unique index if not exists albatros_trasferimenti_movimento_idx on albatros_trasferimenti (movimento_id);

-- Chiuse a chi non è entrato, come tutte le tabelle (vedi sql/accesso_supabase_auth.sql).
alter table albatros_banca_import enable row level security;
drop policy if exists app_accesso on albatros_banca_import;
create policy app_accesso on albatros_banca_import for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

alter table albatros_banca_movimenti enable row level security;
drop policy if exists app_accesso on albatros_banca_movimenti;
create policy app_accesso on albatros_banca_movimenti for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

commit;
