-- ============================================================
-- Albatros: le missioni, cioe' le cose da fare per il centro, e le azioni fatte su ognuna.
-- Da eseguire nell'SQL Editor di Supabase.
--
-- albatros_missioni
--   stato       'aperta' | 'in_corso' | 'in_attesa' | 'chiusa'
--   priorita    'alta' | 'normale' | 'bassa'
--   chiusa_il   quando e' passata a 'chiusa' (null finche' non lo e')
-- albatros_missioni_azioni: cosa e' stato fatto e in che giorno. Anche i cambi di stato
-- lasciano un'azione, cosi' la storia di una missione si legge tutta in un posto.
-- albatros_missioni_attivita: le sotto-attivita' di una missione, ognuna col suo responsabile e la
-- sua scadenza; fatta_il e' quando e' stata spuntata. Fatte tutte, la missione si chiude.
-- Le azioni (cosa e' stato fatto, quando) si scrivono sotto un'attivita' (attivita_id).
-- Si puo' rieseguire: crea solo quello che manca.
-- L'elenco delle scelte sta nell'app (src/moduli/albatros/regoleMissioni.js), non nel database.
-- ============================================================

begin;
set local lock_timeout = '3s';

create table if not exists albatros_missioni (
  id bigint generated by default as identity primary key,
  titolo text not null,
  descrizione text,
  stato text not null default 'aperta',
  priorita text not null default 'normale',
  responsabile_id bigint references utenti(id) on update cascade on delete set null,
  scadenza date,
  chiusa_il timestamptz,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);
create index if not exists albatros_missioni_stato_idx on albatros_missioni (stato);

create table if not exists albatros_missioni_azioni (
  id bigint generated by default as identity primary key,
  missione_id bigint not null references albatros_missioni(id) on delete cascade,
  data date not null,
  descrizione text not null,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);
create index if not exists albatros_missioni_azioni_missione_idx on albatros_missioni_azioni (missione_id, data);

create table if not exists albatros_missioni_attivita (
  id bigint generated by default as identity primary key,
  missione_id bigint not null references albatros_missioni(id) on delete cascade,
  titolo text not null,
  responsabile_id bigint references utenti(id) on update cascade on delete set null,
  scadenza date,
  fatta_il timestamptz,
  fatta_da bigint references utenti(id) on update cascade on delete set null,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);
create index if not exists albatros_missioni_attivita_missione_idx on albatros_missioni_attivita (missione_id);

-- Le azioni stanno sotto l'attivita' a cui si riferiscono. Senza attivita' restano solo i cambi di
-- stato della missione, che sono la sua storia.
alter table albatros_missioni_azioni
  add column if not exists attivita_id bigint references albatros_missioni_attivita(id) on delete cascade;
create index if not exists albatros_missioni_azioni_attivita_idx on albatros_missioni_azioni (attivita_id);

-- Chiuse a chi non è entrato, come tutte le tabelle (vedi sql/accesso_supabase_auth.sql).
alter table albatros_missioni enable row level security;
drop policy if exists app_accesso on albatros_missioni;
create policy app_accesso on albatros_missioni for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

alter table albatros_missioni_azioni enable row level security;
drop policy if exists app_accesso on albatros_missioni_azioni;
create policy app_accesso on albatros_missioni_azioni for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

alter table albatros_missioni_attivita enable row level security;
drop policy if exists app_accesso on albatros_missioni_attivita;
create policy app_accesso on albatros_missioni_attivita for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

commit;
