-- ============================================================
-- Albatros: i pagamenti a Lama e BFM, fatti da Albatros o da BFM.
-- Da eseguire nell'SQL Editor di Supabase.
--
-- Ogni volta che Albatros o BFM danno dei soldi a Lama (o Albatros a BFM) se ne registra il pagamento:
--   pagante       'albatros' | 'bfm'
--   beneficiario  'lama' | 'bfm'
--   causale       'rimborso' (restituisce spese che il beneficiario ha pagato per il centro),
--                 'stipendio' | 'altro'
--   metodo        'contanti' (contanti di chi paga) | 'bonifico' | 'altro'
-- Nel Cashflow i rimborsi abbassano quanto c'e' da rimborsare al beneficiario; i pagamenti in
-- contanti di Albatros abbassano i contanti che Albatros ha in mano; sono uscite di chi paga.
-- L'elenco delle scelte sta nell'app (src/moduli/albatros/calcolo.js), non nel database.
-- ============================================================

begin;
set local lock_timeout = '3s';

create table if not exists albatros_pagamenti (
  id bigint generated by default as identity primary key,
  data date not null,
  pagante text not null,
  beneficiario text not null,
  causale text not null,
  importo numeric(10,2) not null check (importo > 0),
  metodo text not null,
  note text,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);
create index if not exists albatros_pagamenti_beneficiario_idx on albatros_pagamenti (beneficiario, data);

-- Chiusa a chi non è entrato, come tutte le tabelle (vedi sql/accesso_supabase_auth.sql).
alter table albatros_pagamenti enable row level security;
drop policy if exists app_accesso on albatros_pagamenti;
create policy app_accesso on albatros_pagamenti for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

commit;
