-- ============================================================
-- Albatros: i trasferimenti di denaro fra i contanti in mano e il conto.
-- Da eseguire nell'SQL Editor di Supabase.
--
-- Un versamento in banca dei contanti (da = 'contanti') li toglie dai contanti in mano e li
-- aggiunge al conto; un prelievo (da = 'conto') fa il contrario. Il saldo di Albatros non cambia:
-- i soldi passano solo da una tasca all'altra.
-- ============================================================

begin;
set local lock_timeout = '3s';

create table if not exists albatros_trasferimenti (
  id bigint generated by default as identity primary key,
  data date not null,
  da text not null check (da in ('contanti', 'conto')),
  importo numeric(10,2) not null check (importo > 0),
  note text,
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);
create index if not exists albatros_trasferimenti_data_idx on albatros_trasferimenti (data);

-- Chiusa a chi non è entrato, come tutte le tabelle (vedi sql/accesso_supabase_auth.sql).
alter table albatros_trasferimenti enable row level security;
drop policy if exists app_accesso on albatros_trasferimenti;
create policy app_accesso on albatros_trasferimenti for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

commit;
