-- ============================================================
-- Albatros: gli acconti dei clienti.
-- Da eseguire nell'SQL Editor di Supabase.
--
-- Un cliente versa un acconto su una voce del listino (una festa, un campo) per un giorno che deve
-- ancora venire. I soldi entrano subito nel Cashflow (data_versamento, metodo: i contanti nei
-- contanti in mano, POS e bonifico sul conto). Il giorno di riferimento la voce si batte per
-- intero, la sera si incassa il saldo, e l'acconto confermato chiude la differenza: entra
-- nell'incassato di quella giornata, non nel suo POS né nei suoi contanti.
--   stato  'atteso'      versato, il giorno non è ancora arrivato o non è confermato
--          'confermato'  il giorno è arrivato e l'evento c'è stato: è incasso di quella giornata
--          'rimborsato'  disdetto e restituito: esce dal Cashflow il rimborso_data, dai contanti o
--                        dal conto (rimborso_metodo)
--          'trattenuto'  disdetto ma tenuto: è un incasso senza evento
-- L'elenco delle scelte sta nell'app (src/moduli/albatros/calcolo.js), non nel database.
-- ============================================================

begin;
set local lock_timeout = '3s';

create table if not exists albatros_acconti (
  id bigint generated by default as identity primary key,
  cliente text not null check (btrim(cliente) <> ''),
  -- Se la voce si cancella dal listino l'acconto resta, senza voce. Unendo due voci l'app sposta
  -- anche gli acconti.
  voce_id bigint references albatros_listino(id) on delete set null,
  data_riferimento date not null,
  data_versamento date not null,
  importo numeric(10,2) not null check (importo > 0),
  metodo text not null check (metodo in ('contanti', 'pos', 'bonifico')),
  note text,
  stato text not null default 'atteso' check (stato in ('atteso', 'confermato', 'rimborsato', 'trattenuto')),
  esito_il timestamptz,
  esito_da bigint references utenti(id) on update cascade on delete set null,
  rimborso_data date,
  rimborso_metodo text check (rimborso_metodo in ('contanti', 'conto')),
  creato_il timestamptz not null default now(),
  creato_da bigint references utenti(id) on update cascade on delete set null
);
create index if not exists albatros_acconti_riferimento_idx on albatros_acconti (data_riferimento);
create index if not exists albatros_acconti_stato_idx on albatros_acconti (stato);

-- Su quali categorie del listino si prende un acconto (le feste, i campi; il bar no): si cambia
-- dal Configuratore. Di partenza tutte tranne quelle che si chiamano "bar".
do $$
begin
  if not exists (select 1 from information_schema.columns where table_name = 'albatros_categorie' and column_name = 'acconti') then
    alter table albatros_categorie add column acconti boolean not null default true;
    update albatros_categorie set acconti = false where tipo = 'listino' and lower(nome) like '%bar%';
  end if;
end $$;

-- Chiusa a chi non è entrato, come tutte le tabelle (vedi sql/accesso_supabase_auth.sql).
alter table albatros_acconti enable row level security;
drop policy if exists app_accesso on albatros_acconti;
create policy app_accesso on albatros_acconti for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

commit;
