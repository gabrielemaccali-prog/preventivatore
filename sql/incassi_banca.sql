-- ============================================================
-- Incassi: gli accrediti dell'estratto conto abbinati ai pagamenti dell'app.
-- Da eseguire nell'SQL Editor di Supabase.
--
-- 1. pagamenti.movimento_id: il movimento di banca che ha portato quei soldi. Un accredito può
--    portarne più d'uno (le quote di un bonifico su più prenotazioni, o due pagamenti versati
--    insieme); un pagamento viene da un accredito solo. Se il movimento sparisce, il pagamento
--    resta e torna da abbinare.
--
-- 2. incassi_categorie: per gli accrediti che non vengono da una prenotazione né da un voucher
--    (capitale versato, una vendita, un rimborso). Le decide il Configuratore delle spese.
--
-- 3. banca_movimenti.incasso_categoria_id: la categoria di un accredito senza abbinamento.
--
-- Additive: niente di quello che c'è cambia.
-- ============================================================

begin;
set local lock_timeout = '3s';

create table if not exists incassi_categorie (
  id bigint generated by default as identity primary key,
  nome text not null check (btrim(nome) <> ''),
  ordine integer not null default 0,
  attiva boolean not null default true,
  creato_il timestamptz not null default now()
);
create unique index if not exists incassi_categorie_nome_idx on incassi_categorie (lower(btrim(nome)));

alter table banca_movimenti add column if not exists incasso_categoria_id bigint references incassi_categorie(id) on delete restrict;

alter table pagamenti add column if not exists movimento_id bigint references banca_movimenti(id) on delete set null;
create index if not exists pagamenti_movimento_idx on pagamenti (movimento_id) where movimento_id is not null;

-- Chiusa a chi non e' entrato, come tutte le tabelle (vedi sql/accesso_supabase_auth.sql).
alter table incassi_categorie enable row level security;
drop policy if exists app_accesso on incassi_categorie;
create policy app_accesso on incassi_categorie for all to authenticated
  using ((select riservato.puo_operare())) with check ((select riservato.puo_operare()));

commit;

-- Controllo: le colonne e la tabella ci sono.
select
  (select count(*) from incassi_categorie) as categorie,
  (select count(*) from pagamenti where movimento_id is not null) as pagamenti_abbinati,
  (select count(*) from banca_movimenti where incasso_categoria_id is not null) as accrediti_con_categoria;
